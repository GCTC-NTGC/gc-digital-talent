"""
Builds one self-contained file per page in azure/, with common.py, queries.py and any other
page script it imports inlined, so a test can be created in the Azure Load Testing portal by
uploading a single file.

Usage (from apps/locust, after changing any of the scripts):
  python3 bundle.py
"""

from pathlib import Path

HERE = Path(__file__).parent
# Page script: other page scripts it imports
PAGES = {
    "search_page": [],
    "browse_jobs_page": [],
    "job_poster_page": [],
    "public_journeys": ["search_page"],
}

TEMPLATE = '''# Generated by bundle.py from {sources}. Do not edit by hand.
# Upload this single file as the Locust test script in Azure Load Testing.
import sys
import types


def _module(name, source):
    module = types.ModuleType(name)
    sys.modules[name] = module
    exec(compile(source, name + ".py", "exec"), module.__dict__)
    return module


{modules}

{page_source}'''


def main():
    out = HERE / "azure"
    out.mkdir(exist_ok=True)
    for page, imports in PAGES.items():
        names = ["queries", "common", *imports]
        modules = "\n".join(f"_module({name!r}, {(HERE / f'{name}.py').read_text()!r})" for name in names)
        page_source = (HERE / f"{page}.py").read_text()
        sources = ", ".join(f"{name}.py" for name in [page, *names])
        (out / f"{page}.py").write_text(TEMPLATE.format(sources=sources, modules=modules, page_source=page_source))
        print(f"Wrote azure/{page}.py")


if __name__ == "__main__":
    main()
